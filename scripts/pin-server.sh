#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
TARGET_FILE="${ROOT_DIR}/src/pinned.rs"

REPO="adrijshikhar/htmx-analyzer"
WORKFLOW="adrijshikhar/htmx-analyzer/.github/workflows/release.yml"

PLATFORMS=(
    "darwin-arm64:htmx-analyzer-darwin-arm64"
    "darwin-x64:htmx-analyzer-darwin-x64"
    "linux-x64:htmx-analyzer-linux-x64"
    "linux-arm64:htmx-analyzer-linux-arm64"
    "windows-x64:htmx-analyzer-windows-x64.exe"
    "windows-arm64:htmx-analyzer-windows-arm64.exe"
)

compute_sha256() {
    local file="$1"
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$file" | awk '{print $1}'
    elif command -v shasum >/dev/null 2>&1; then
        shasum -a 256 "$file" | awk '{print $1}'
    else
        echo "Error: neither sha256sum nor shasum found" >&2
        exit 1
    fi
}

usage() {
    echo "Usage: $0 <tag> | --check" >&2
    exit 1
}

if [ $# -ne 1 ]; then
    usage
fi

CHECK_MODE=0
TAG=""

if [ "$1" = "--check" ]; then
    CHECK_MODE=1
    if [ ! -f "$TARGET_FILE" ]; then
        echo "Error: target file $TARGET_FILE does not exist" >&2
        exit 1
    fi
    TAG=$(sed -n -E 's/^[[:space:]]*pub const SERVER_TAG: &str = "([^"]+)";/\1/p' "$TARGET_FILE")
    if [ -z "$TAG" ]; then
        echo "Error: could not extract SERVER_TAG from $TARGET_FILE" >&2
        exit 1
    fi
else
    TAG="$1"
fi

if ! command -v gh >/dev/null 2>&1; then
    echo "Error: gh (GitHub CLI) is required" >&2
    exit 1
fi

TMP_DIR=$(mktemp -d)
TMP_OUTPUT=$(mktemp)

cleanup() {
    rm -rf "$TMP_DIR" "$TMP_OUTPUT"
}
trap cleanup EXIT

echo "Fetching and verifying assets for ${REPO} at tag ${TAG}..."

cat <<EOF > "$TMP_OUTPUT"
// @generated by scripts/pin-server.sh — do not edit
pub const SERVER_TAG: &str = "${TAG}";
pub const ASSETS: &[(&str, &str, &str)] = &[
EOF

for entry in "${PLATFORMS[@]}"; do
    key="${entry%%:*}"
    asset="${entry##*:}"

    echo "==> Processing $asset ($key)..."
    gh release download "$TAG" -R "$REPO" -p "$asset" -p "${asset}.sha256" -D "$TMP_DIR"

    binary_file="${TMP_DIR}/${asset}"
    sha_file="${TMP_DIR}/${asset}.sha256"

    if [ ! -f "$binary_file" ] || [ ! -f "$sha_file" ]; then
        echo "Error: failed to download $asset or ${asset}.sha256" >&2
        exit 1
    fi

    echo "Verifying attestation for $asset..."
    gh attestation verify "$binary_file" \
        -R "$REPO" \
        --signer-workflow "$WORKFLOW" \
        --source-ref "refs/tags/${TAG}"

    computed_sha=$(compute_sha256 "$binary_file")
    expected_sha=$(awk '{print $1}' "$sha_file" | tr '[:upper:]' '[:lower:]')

    if [ "$computed_sha" != "$expected_sha" ]; then
        echo "Error: SHA-256 mismatch for ${asset}: expected ${expected_sha}, got ${computed_sha}" >&2
        exit 1
    fi

    cat <<EOF >> "$TMP_OUTPUT"
    (
        "${key}",
        "${asset}",
        "${computed_sha}",
    ),
EOF
done

cat <<EOF >> "$TMP_OUTPUT"
];
EOF

if [ "$CHECK_MODE" -eq 1 ]; then
    if diff -u "$TARGET_FILE" "$TMP_OUTPUT"; then
        echo "Pinned hashes check passed for ${TAG}."
        exit 0
    else
        echo "Error: pinned hashes drift detected between $TARGET_FILE and generated release ${TAG}!" >&2
        exit 1
    fi
else
    cp "$TMP_OUTPUT" "$TARGET_FILE"
    echo "Successfully updated $TARGET_FILE for ${TAG}."
fi
